/**
 * Writes golang/scripts_version.go with the version of this package (the
 * root package.json), whose Lua and SQL scripts the Go module embeds. Go
 * queues store it in their metadata as `bullmq:<version>`, as Node's Queue
 * does, so dashboards enable the features of the scripts' version.
 *
 * Run by `yarn copy:lua:golang` and `yarn copy:sql:golang`, next to the
 * scripts it describes. The output is gitignored, like the scripts.
 */

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const { version } = JSON.parse(
  fs.readFileSync(path.join(root, 'package.json'), 'utf8'),
);
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`Unexpected package.json version: ${version}`);
  process.exit(1);
}

const content = `// Code generated by scripts/generateGolangScriptsVersion.js from the root package.json; DO NOT EDIT.

package bullmq

// ScriptsVersion is the version of the Node.js BullMQ package whose Lua and
// SQL scripts this module embeds. Queues store it in their metadata as
// \`bullmq:<ScriptsVersion>\`, as Node's Queue does, so that dashboards enable
// the features of that version. [Version] is the version of this module.
const ScriptsVersion = "${version}"
`;

fs.writeFileSync(path.join(root, 'golang', 'scripts_version.go'), content);
